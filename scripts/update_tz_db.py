#!/usr/bin/env python3
"""Generate include/TimezoneDB.h from nayarsystems/posix_tz_db zones.csv."""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import urllib.request

DEFAULT_ZONES_URL = (
    "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.csv"
)
DEFAULT_OUTPUT_PATH = os.path.join("include", "TimezoneDB.h")


def c_escape(value: str) -> str:
    """Escape a string for safe inclusion in a C++ double-quoted literal."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def load_csv_text(input_path: str | None, url: str) -> str:
    """Load zones.csv contents from a local path or the upstream URL."""
    if input_path:
        with open(input_path, "r", encoding="utf-8") as f:
            return f.read()
    with urllib.request.urlopen(url, timeout=15) as resp:
        return resp.read().decode("utf-8")


def parse_zones(csv_text: str) -> dict[str, str]:
    """Parse IANA -> POSIX timezone mappings from CSV text."""
    zones: dict[str, str] = {}
    reader = csv.reader(io.StringIO(csv_text))
    for row in reader:
        if len(row) < 2:
            continue
        iana = row[0].strip()
        posix = row[1].strip()
        if not iana or not posix:
            continue
        if iana.lower() in ("timezone", "zone", "iana") and posix.lower() in (
            "posix",
            "posix_tz",
            "tz",
        ):
            continue
        zones[iana] = posix

    # Modern browsers' Intl APIs return Europe/Kyiv instead of Europe/Kiev.
    if "Europe/Kiev" in zones and "Europe/Kyiv" not in zones:
        zones["Europe/Kyiv"] = zones["Europe/Kiev"]

    return zones


def build_regions(sorted_zones: list[tuple[str, str]]) -> dict[str, list[str]]:
    """Group IANA timezone names into sorted {region: [city, ...]} buckets."""
    regions: dict[str, list[str]] = {}
    for iana, _ in sorted_zones:
        if "/" not in iana:
            continue
        region, city = iana.split("/", 1)
        regions.setdefault(region, []).append(city)
    return {region: sorted(cities) for region, cities in sorted(regions.items())}


def render_header(
    sorted_zones: list[tuple[str, str]], regions: dict[str, list[str]]
) -> str:
    """Render the C++14-compatible include/TimezoneDB.h header contents."""
    entries_lines = [
        f'    {{"{c_escape(iana)}", "{c_escape(posix)}"}},'
        for iana, posix in sorted_zones
    ]
    regions_json = json.dumps(regions, separators=(",", ":"), ensure_ascii=True)

    return "\n".join(
        [
            "#pragma once",
            "",
            "// Generated by scripts/update_tz_db.py",
            "// Source data: https://github.com/nayarsystems/posix_tz_db (MIT License)",
            "",
            "#include <cstddef>",
            "#include <cstring>",
            "",
            "struct TimezoneEntry {",
            "    const char* iana;",
            "    const char* posix;",
            "};",
            "",
            "// Sorted strictly by ASCII byte order for binary search via std::strcmp.",
            "static constexpr TimezoneEntry kTimezones[] = {",
            *entries_lines,
            "};",
            "",
            "static constexpr size_t kTimezoneCount =",
            "    sizeof(kTimezones) / sizeof(kTimezones[0]);",
            "",
            "inline const TimezoneEntry* findTimezoneEntry(const char* tz) {",
            "    if (!tz || tz[0] == '\\0') {",
            "        return nullptr;",
            "    }",
            "    size_t lo = 0;",
            "    size_t hi = kTimezoneCount;",
            "    while (lo < hi) {",
            "        size_t mid = lo + (hi - lo) / 2;",
            "        int cmp = std::strcmp(kTimezones[mid].iana, tz);",
            "        if (cmp == 0) {",
            "            return &kTimezones[mid];",
            "        }",
            "        if (cmp < 0) {",
            "            lo = mid + 1;",
            "        } else {",
            "            hi = mid;",
            "        }",
            "    }",
            "    return nullptr;",
            "}",
            "",
            "inline bool isKnownIanaTimezone(const char* tz) {",
            "    return findTimezoneEntry(tz) != nullptr;",
            "}",
            "",
            "inline const char* lookupPosixTimezone(const char* tz) {",
            "    if (!tz || tz[0] == '\\0') {",
            '        return "UTC0";',
            "    }",
            "    const TimezoneEntry* entry = findTimezoneEntry(tz);",
            "    return entry ? entry->posix : tz;",
            "}",
            "",
            '#define TIMEZONE_REGIONS_JS R"tzjs(',
            f"const TIMEZONE_REGIONS = {regions_json};",
            ')tzjs"',
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate include/TimezoneDB.h from nayarsystems/posix_tz_db."
    )
    parser.add_argument(
        "--input",
        help="Optional local path to zones.csv instead of fetching from GitHub.",
    )
    parser.add_argument(
        "--url",
        default=DEFAULT_ZONES_URL,
        help="Source URL for zones.csv.",
    )
    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT_PATH,
        help="Output header path (default: include/TimezoneDB.h).",
    )
    args = parser.parse_args()

    csv_text = load_csv_text(args.input, args.url)
    zones = parse_zones(csv_text)
    if not zones:
        raise RuntimeError("No timezone entries parsed from zones.csv")

    # Sort by raw ASCII byte order to match std::strcmp binary search.
    sorted_zones = sorted(zones.items(), key=lambda kv: kv[0].encode("ascii"))
    regions = build_regions(sorted_zones)
    header = render_header(sorted_zones, regions)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)

    print(
        f"Generated {args.output} with {len(sorted_zones)} timezones "
        f"across {len(regions)} regions."
    )


if __name__ == "__main__":
    main()
